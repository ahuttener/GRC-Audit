import type { AuditResult, AuditResponse } from "@/types/grc";

/** Render an AuditResponse as a shareable Markdown audit report. */
export function toMarkdown(resp: AuditResponse): string {
  const r: AuditResult = resp.result;
  const gf = r.grounded_frameworks;
  const L: string[] = [];

  L.push(`# ${r.incident_title}`);
  L.push("");
  L.push(`**Severity:** ${r.severity_level}  `);
  L.push(`**Failure category:** ${r.failure_category}  `);
  L.push(
    `**Engine:** ${resp.source === "llm" ? `LLM (${resp.model ?? "model"})` : "Local demo engine"}  `
  );
  L.push(
    `**Grounding:** ${resp.verification.grounded ? "All cited control IDs verified against local catalogs ✓" : `${resp.verification.unverified.length} unverified ID(s)`}`
  );
  L.push(
    `**Recommended strategy:** ${r.recommended_strategy?.strategy ?? "MITIGATE"} — ${r.recommended_strategy?.rationale ?? ""}`
  );
  L.push("");
  L.push(`## Executive summary`);
  L.push(r.incident_summary);
  L.push("");
  L.push(`## Grounded framework mapping`);
  L.push(`### NIST CSF 2.0 — ${gf.nist_csf_2.function_name}`);
  L.push(`- **${gf.nist_csf_2.subcategories}**`);
  L.push(`### ISO/IEC 27001:2022 — ${gf.iso_27001_2022.category}`);
  L.push(`- **${gf.iso_27001_2022.control_id} — ${gf.iso_27001_2022.control_name}:** ${gf.iso_27001_2022.audit_finding}`);
  L.push(`### SOC 2 — ${gf.soc_2.name}`);
  L.push(`- **${gf.soc_2.criteria}:** ${gf.soc_2.audit_finding}`);
  L.push(`### GDPR — ${gf.gdpr.name}`);
  L.push(`- **${gf.gdpr.article}:** ${gf.gdpr.regulatory_risk}`);
  L.push(`### CCPA/CPRA — ${gf.ccpa_cpra.name}`);
  L.push(`- **${gf.ccpa_cpra.section}:** ${gf.ccpa_cpra.regulatory_risk}`);
  L.push(`### HIPAA — ${gf.hipaa.name}`);
  L.push(`- **${gf.hipaa.rule}:** ${gf.hipaa.regulatory_risk}`);
  L.push(`### AIUC-1 (AI agents) — ${gf.aiuc_1?.name ?? "AI agent standard"}`);
  L.push(`- **${gf.aiuc_1?.requirements ?? "N/A"}:** ${gf.aiuc_1?.audit_finding ?? "Not applicable — no AI system or agent is involved."}`);
  L.push("");
  L.push(`## Audit evidence required`);
  for (const e of r.audit_evidence_required) L.push(`- ${e}`);
  L.push("");
  L.push(`## Remediation plan`);
  L.push(`**1. Immediate containment.** ${r.remediation_plan.step_1_containment}`);
  L.push("");
  L.push(`**2. Data-leak investigation & legal.** ${r.remediation_plan.step_2_leak_and_legal}`);
  L.push("");
  L.push(`**3. Permanent systemic fix.** ${r.remediation_plan.step_3_permanent_fix}`);
  L.push("");
  L.push(`---`);
  L.push(`_Generated by GRC Audit (CyberSecInfo). Grounded against embedded official catalogs; automated output is an indicator, not legal advice — confirm with a qualified assessor._`);
  return L.join("\n");
}
